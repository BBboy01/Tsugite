function detectLanguage(): LanguageCode {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem("iris.language");
  if (languageOptions.some((option) => option.code === stored)) return stored as LanguageCode;
  const browserLanguage = navigator.language.toLowerCase();
  if (browserLanguage.startsWith("zh-tw") || browserLanguage.startsWith("zh-hk")) return "zh-TW";
  if (browserLanguage.startsWith("zh")) return "zh-CN";
  if (browserLanguage.startsWith("ja")) return "ja";
  return "en";
}

function syncLanguageMetadata(language: string): void {
  if (typeof document !== "undefined") document.documentElement.lang = language;
  if (typeof window !== "undefined") window.localStorage.setItem("iris.language", language);
}

i18n.on("languageChanged", syncLanguageMetadata);

void i18n
  .use(initReactI18next)
  .init({
    fallbackLng: "en",
    interpolation: { escapeValue: false },
    keySeparator: false,
    lng: detectLanguage(),
    resources,
    supportedLngs: languageOptions.map((option) => option.code),
  })
  .then(() => syncLanguageMetadata(i18n.language));

export default i18n;
